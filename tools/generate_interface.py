"""Regenerate checked-in interface constants; --check detects ABI drift."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads((ROOT / "spec/interface.json").read_text())
    python = "# Generated by tools/generate_interface.py.\nfrom enum import IntEnum\n\n"
    python += "\n".join(
        f"{name} = {address}" for name, address in spec["registers"].items()
    )
    python += "\n\nclass Status(IntEnum):\n" + "".join(
        f"    {name} = {value}\n" for name, value in spec["statuses"].items()
    )
    verilog = "// Generated by tools/generate_interface.py.\n"
    verilog += "".join(
        f"localparam R_{name} = {address};\n"
        for name, address in spec["registers"].items()
    )
    verilog += "".join(
        f"localparam {name} = {value};\n" for name, value in spec["statuses"].items()
    )
    table = "# BAR register reference\n\nAll values are little-endian 32-bit words. BAR0 is 128 KiB.\n\n| Name | Offset |\n|---|---:|\n"
    table += "".join(
        f"| {name} | `0x{value:04x}` |\n" for name, value in spec["registers"].items()
    )
    table += (
        "\nRegion records start at `0x100`, stride 32, count 16: base low/high (+0/+4), size low/high (+8/+12), generation (+16), permissions (+20). They are write-only; unused fields return AXI SLVERR. FPGA RAM begins at `0x10000`; the last 16 bytes are private.\n\nStatus codes: "
        + ", ".join(f"{name}={value}" for name, value in spec["statuses"].items())
        + ".\n"
    )
    for path, content in [
        (ROOT / "python/fpga_dma_lab/registers.py", python),
        (ROOT / "rtl/interface.svh", verilog),
        (ROOT / "docs/registers.md", table),
    ]:
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Out of date: {path}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
